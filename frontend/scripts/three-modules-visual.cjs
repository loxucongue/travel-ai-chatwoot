const { chromium } = require('C:/Users/24159/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright');
const fs = require('fs');
const path = require('path');
const assert = require('assert');
const root = path.resolve(__dirname, '../..');
const output = path.join(root, 'output/three-modules-20260826');
(async () => {
  const credentials = JSON.parse(fs.readFileSync(path.join(root, '.runlogs/three-qa-credentials.json'), 'utf8'));
  const result = JSON.parse(fs.readFileSync(path.join(output, 'playwright-result.json'), 'utf8'));
  const browser = await chromium.launch({ channel: 'msedge', headless: true });
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
  await page.goto('http://127.0.0.1:4175/');
  await page.locator('input[type=email]').fill(credentials.email);
  await page.locator('input[type=password]').fill(credentials.password);
  await page.getByRole('button', { name: /登录/ }).click();
  await page.waitForURL('**/#/overview');
  await page.goto(result.populatedSession);
  await page.locator('.playground-message.customer').first().waitFor();
  await page.waitForTimeout(500);
  const customer = await page.locator('.playground-message.customer > div').first().boundingBox();
  const assistant = await page.locator('.playground-message.assistant > div').first().boundingBox();
  assert(customer.x < assistant.x, 'Message alignment');
  assert(!(await page.locator('body').innerText()).includes('Invalid Date'));
  await page.screenshot({ path: path.join(output, 'screenshots/playground-final-desktop.png'), fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  await page.waitForTimeout(500);
  const sidebar = await page.locator('.sidebar').boundingBox();
  assert(sidebar.x + sidebar.width <= 1, 'Mobile sidebar covers chat');
  await page.screenshot({ path: path.join(output, 'screenshots/playground-populated-mobile.png'), fullPage: true });
  await page.getByRole('button', { name: '打开导航', exact: true }).click();
  await page.waitForTimeout(300);
  await page.getByRole('button', { name: '沉默客户唤醒', exact: true }).click();
  await page.getByRole('button', { name: '新建策略', exact: true }).waitFor();
  await page.waitForTimeout(400);
  assert((await page.locator('.sidebar').boundingBox()).x < 0);
  await page.screenshot({ path: path.join(output, 'screenshots/wakeup-final-mobile.png'), fullPage: true });
  await browser.close();
  fs.writeFileSync(path.join(output, 'visual-result.json'), JSON.stringify({ status: 'passed', leftRightAlignment: true, timestamps: true, mobileSidebar: true, mobileNavigation: true }, null, 2));
  console.log('Visual layout checks passed');
})().catch(error => { console.error(error); process.exit(1); });
