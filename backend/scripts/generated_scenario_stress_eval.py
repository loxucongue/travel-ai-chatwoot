def reply_style_limit(key: str, default: int) -> int:
    """Read current policy limits while tolerating older report schemas."""
    return int(
        (JOURNEY_POLICY.get("reply_style") or {}).get(key)
        or (JOURNEY_POLICY.get("reply_limits") or {}).get(key)
        or default
    )


@dataclass
class Scenario:
    case_id: str
    suite: str
    customer_text: str
    expected_route: str = ""
    expected_action: str = "reply"
    expected_branch: str | None = None
    expected_groups_any: list[str] = field(default_factory=list)
    expected_refs_any: list[str] = field(default_factory=list)
    expected_slots: dict[str, str] = field(default_factory=dict)
    expected_lead_action: str | None = None
    expected_handoff_reason: str | None = None
    context_messages: list[dict[str, str]] = field(default_factory=list)
    current_route: str = ""
    memory: dict[str, Any] = field(default_factory=dict)
    journey_stage: str = "route_selection"
    sent_groups: list[str] = field(default_factory=list)
    lead_capture_status: str = "not_started"
    current_attachments: list[dict[str, Any]] = field(default_factory=list)
    flags: set[str] = field(default_factory=set)


def counts() -> dict[str, int]:
    with SessionLocal() as db:
        return {
            "outbound": int(db.scalar(select(func.count()).select_from(OutboundMessage)) or 0),
            "handoff": int(db.scalar(select(func.count()).select_from(HandoffTask)) or 0),
        }


def context(*items: tuple[str, str]) -> list[dict[str, str]]:
    return [{"direction": direction, "content": content} for direction, content in items]


def memory(**slots: str) -> dict[str, dict[str, str]]:
    return {key: {"value": value, "evidence": value} for key, value in slots.items()}


