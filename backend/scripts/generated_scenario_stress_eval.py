    print(json.dumps({
        "output_dir": str(output_dir),
        "total_cases": summary["total_cases"],
        "business_pass_rate": summary["business_pass_rate"],
        "target_met": summary["target_met"],
        "side_effect_free": summary["side_effect_free"],
        "infrastructure_failed": summary["infrastructure_failed"],
    }, ensure_ascii=False, indent=2))
    return 0 if summary["target_met"] and summary["side_effect_free"] and summary["infrastructure_failed"] == 0 else 1


